/// Look up one interface string; unknown keys return the key itself.
fn table(l: Lang) -> &'static [(&'static str, &'static str)] {
    match l {
        Lang::En => EN,
        Lang::Zh => ZH,
        Lang::Es => ES,
        Lang::Ja => JA,
        Lang::De => DE,
        Lang::It => IT,
    }
}

pub fn t(key: &str) -> &'static str {
    let l = lang();
    if let Some(v) = table(l).iter().find(|(k, _)| *k == key).map(|(_, v)| *v) {
        return v;
    }
    // Missing translations fall back to English, then to the key itself.
    table(Lang::En)
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, v)| *v)
        .unwrap_or("")
}

/// Same, substituting `{}` placeholders in order.
pub fn tf(key: &str, args: &[&str]) -> String {
    let mut out = t(key).to_string();
    for a in args {
        if let Some(i) = out.find("{}") {
            out.replace_range(i..i + 2, a);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_is_default() {
        set("en");
        assert_eq!(t("on"), "on");
        assert!(tf("force_sent", &["hi"]).contains("hi"));
    }

    #[test]
    fn chinese_switch() {
        set("zh");
        assert_eq!(t("on"), "开");
        assert!(tf("queued", &["2"]).contains('2'));
        set("en");
    }

    #[test]
    fn every_language_covers_the_english_catalog() {
        let en: Vec<&str> = table(Lang::En).iter().map(|(k, _)| *k).collect();
        for l in [Lang::Zh, Lang::Es, Lang::Ja, Lang::De, Lang::It] {
            let have: std::collections::HashSet<&str> =
                table(l).iter().map(|(k, _)| *k).collect();
            let missing: Vec<&str> = en.iter().copied().filter(|k| !have.contains(k)).collect();
            assert!(missing.is_empty(), "language {:?} misses: {:?}", l, missing);
        }
    }

    #[test]
    fn new_ui_keys_are_translated() {
        for code in ["es", "ja", "de", "it"] {
            set(code);
            assert!(!t("approval_title").is_empty());
            assert!(!t("cfg_help_sandbox").is_empty());
            assert!(!t("tip1").is_empty());
        }
        set("es");
        assert!(t("approval_title").contains("Permiso"), "{}", t("approval_title"));
        set("ja");
        assert!(t("approval_title").contains("権限"), "{}", t("approval_title"));
        set("en");
    }

    #[test]
    fn new_languages_switch_and_fallback() {
        for (code, hint) in [
            ("es", "mantén Tab"),
            ("ja", "Tab 長押し"),
            ("de", "Tab halten"),
            ("it", "tieni Tab"),
        ] {
            set(code);
            assert_eq!(self::code(), code);
            assert!(t("hints").contains(hint), "{code} hints: {}", t("hints"));
            // Keys missing from a translation table fall back to English.
            assert!(!t("menu_custom").is_empty(), "{code} fallback missing");
        }
        set("en");
        assert_eq!(t("on"), "on");
    }
}
